import { fileURLToPath, URL } from 'node:url'

import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

/**
 * Two builds come out of this config.
 *
 *   pnpm build:client -> dist/client  (the SPA shell + the storefront's hydration
 *                                      bundle, with a manifest so the server can
 *                                      find the hashed filenames)
 *   pnpm build:server -> dist/server  (the storefront's SSR renderer, for Node)
 *
 * `isSsrBuild` is passed by Vite when `--ssr` is used, which is what distinguishes
 * them — the alternative, a second config file, duplicates the plugin and alias
 * setup and then drifts from it.
 */
export default defineConfig(({ isSsrBuild }) => ({
  plugins: [react(), tailwindcss()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    port: 5173,
    // Storefronts resolve by subdomain ({slug}.selld.ph). Allow wildcard hosts in
    // dev so `foo.localhost:5173` reaches the same server as the dashboard.
    host: true,
  },
  build: {
    // Sellers are on mid-range Android phones over mobile data. The storefront
    // carries the stricter budget — see docs/phase-status.md.
    chunkSizeWarningLimit: 600,
    sourcemap: true,
    ...(isSsrBuild
      ? {
          outDir: 'dist/server',
          // Not minified: this runs in Node, where the only cost of readable
          // output is disk, and a legible stack trace from a failed production
          // render is worth more than that.
          minify: false,
        }
      : {
          outDir: 'dist/client',
          // The server reads this to resolve the storefront entry's hashed
          // filename and its stylesheet.
          manifest: true,
          rollupOptions: {
            input: {
              // The dashboard SPA, still entirely client-rendered.
              app: fileURLToPath(new URL('./index.html', import.meta.url)),
              // The storefront's hydration entry, built as its own input: the
              // storefront's HTML is generated by the server, so nothing reaches
              // this module from index.html.
              storefront: fileURLToPath(
                new URL('./src/storefront/entry-client.tsx', import.meta.url),
              ),
            },
          },
        }),
  },
}))
